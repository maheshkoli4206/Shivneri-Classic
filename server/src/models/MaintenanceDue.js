import mongoose from 'mongoose';

const maintenanceDueSchema = new mongoose.Schema(
  {
    // Reference to the Resident master record
    residentId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Resident',
      required: [true, 'सभासद आयडी आवश्यक आहे (Resident ID is required)']
    },
    // Snapshot of resident name at the time of bill generation
    residentNameSnapshot: {
      type: String,
      required: [true, 'सभासदाचे नाव आवश्यक आहे (Resident name snapshot is required)'],
      trim: true
    },
    // Snapshot of flat number at the time of bill generation
    flatNumberSnapshot: {
      type: String,
      trim: true,
      default: ''
    },
    // Building Wing
    wing: {
      type: String,
      default: 'A Wing',
      trim: true
    },
    // Category & Property Type Snapshots at generation time
    propertyTypeSnapshot: {
      type: String,
      enum: ['RESIDENTIAL_FLAT', 'SHOP'],
      default: 'RESIDENTIAL_FLAT'
    },
    maintenanceCategorySnapshot: {
      type: String,
      enum: ['RESIDENTIAL', 'SHOP', 'CHAIRMAN', 'UNASSIGNED'],
      default: 'RESIDENTIAL'
    },
    appliedRate: {
      type: Number,
      default: 1000,
      min: [0, 'दर ० किंवा जास्त असावा']
    },
    // Standard category rate snapshot before any resident or monthly override
    standardRateSnapshot: {
      type: Number,
      default: null
    },
    // Master resident-specific custom rate snapshot if configured
    customMasterRateSnapshot: {
      type: Number,
      default: null
    },
    // Flag indicating whether this month's bill had a temporary override
    isMonthlyOverride: {
      type: Boolean,
      default: false
    },
    // Flag indicating zero-amount bill (PAID with ₹0 balance)
    isZeroAmountBill: {
      type: Boolean,
      default: false
    },
    // Administrative reason for reduced/zero/override bill
    overrideReason: {
      type: String,
      default: '',
      trim: true
    },
    // Billing Period: Month (1 to 12) & Year
    month: {
      type: Number,
      required: [true, 'महिना आवश्यक आहे (Month is required)'],
      min: [1, 'महिना १ ते १२ दरम्यान असावा'],
      max: [12, 'महिना १ ते १२ दरम्यान असावा']
    },
    year: {
      type: Number,
      required: [true, 'वर्ष आवश्यक आहे (Year is required)'],
      min: [2020, 'अवैध वर्ष (Invalid year)']
    },
    // Financial Breakdown
    maintenanceAmount: {
      type: Number,
      required: [true, 'देखभाल आकार आवश्यक आहे (Maintenance amount is required)'],
      min: [0, 'रक्कम ० किंवा जास्त असावी']
    },
    lateFee: {
      type: Number,
      default: 0,
      min: [0, 'विलंब शुल्क ० किंवा जास्त असावे']
    },
    totalAmountDue: {
      type: Number,
      required: [true, 'एकूण देय रक्कम आवश्यक आहे (Total amount due is required)'],
      min: [0, 'रक्कम ० किंवा जास्त असावी']
    },
    // Amount paid: Strictly 0 initially (Payment recording belongs to Phase 6)
    amountPaid: {
      type: Number,
      default: 0,
      min: [0, 'भरलेली रक्कम ० किंवा जास्त असावी']
    },
    // Advance amount applied/adjusted towards this bill
    advanceAdjustedAmount: {
      type: Number,
      default: 0,
      min: [0, 'अ‍ॅडव्हान्स रक्कम ० किंवा जास्त असावी']
    },
    isAdvanceApplied: {
      type: Boolean,
      default: false
    },
    advanceAdjustmentDetails: [
      {
        advancePaymentId: {
          type: mongoose.Schema.Types.ObjectId,
          ref: 'AdvancePayment'
        },
        receiptNumber: {
          type: String,
          trim: true
        },
        amount: {
          type: Number,
          min: 0
        },
        adjustedAt: {
          type: Date,
          default: Date.now
        },
        adjustedByAdminId: {
          type: mongoose.Schema.Types.ObjectId,
          ref: 'Admin'
        }
      }
    ],
    // Outstanding balance: initially equals totalAmountDue
    outstandingBalance: {
      type: Number,
      required: [true, 'शिल्लक रक्कम आवश्यक आहे (Outstanding balance is required)'],
      min: [0, 'रक्कम ० किंवा जास्त असावी']
    },
    // Bill payment status
    status: {
      type: String,
      enum: ['UNPAID', 'PARTIAL', 'PAID'],
      default: 'UNPAID'
    },
    // Payment due date
    dueDate: {
      type: Date,
      required: [true, 'देय तारीख आवश्यक आहे (Due date is required)']
    },
    // Generated by Super Admin
    generatedByAdminId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Admin',
      default: null
    }
  },
  {
    timestamps: true
  }
);

// CRITICAL COMPOUND UNIQUE INDEX: Strictly enforces one bill per resident per month/year
maintenanceDueSchema.index({ residentId: 1, month: 1, year: 1 }, { unique: true });

// Performance indexes for filtering
maintenanceDueSchema.index({ month: 1, year: 1 });
maintenanceDueSchema.index({ status: 1 });

const MaintenanceDue = mongoose.model('MaintenanceDue', maintenanceDueSchema);

export default MaintenanceDue;

