const LanguageContext = createContext(null);

export const LanguageProvider = ({ children }) => {
  // Initialize from localStorage with fallback to authentic Marathi ('mr')
  const [lang, setLangState] = useState(() => {
    try {
      const stored = localStorage.getItem('shivneri_lang');
      if (stored === 'en' || stored === 'mr') {
        return stored;
      }
    } catch {
      // Ignore localStorage read errors in restricted contexts
    }
    return 'mr';
  });

  const setLang = (nextLang) => {
    const valid = nextLang === 'en' ? 'en' : 'mr';
    setLangState(valid);
    try {
      localStorage.setItem('shivneri_lang', valid);
    } catch {
      // Ignore write errors
    }
  };

  const toggleLanguage = () => {
    setLang(lang === 'mr' ? 'en' : 'mr');
  };

  const t = (key) => {
    return translations[lang]?.[key] || translations.mr[key] || key;
  };

  const tMonth = (mNum) => {
    const idx = Number(mNum);
    if (isNaN(idx) || idx < 1 || idx > 12) return String(mNum);
    return lang === 'mr' ? MONTH_NAMES_MR[idx] : MONTH_NAMES_EN[idx];
  };

  return (
    <LanguageContext.Provider value={{ lang, setLang, toggleLanguage, t, tMonth, MONTH_NAMES_MR, MONTH_NAMES_EN }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};

export default LanguageContext;
